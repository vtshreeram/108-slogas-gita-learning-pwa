"""Merge machine-corrected Tamil purports into src/data/purports/chapter-N.json.

Usage: python3 scripts/merge_tamil_purport_corrections.py <work dir>

<work dir>/in/p-NNN.json   OCR paragraphs given to the correcting agents ({verse key: [paragraphs]})
<work dir>/out/p-NNN.json  their corrected paragraphs, same keys, plus an "uncertain" list

A corrected purport replaces the OCR text only if it passes mechanical guards (same paragraph
count, length within 12% per paragraph, Tamil letters only, no invalid vowel-sign sequences, no
stray Latin/digits). Anything else keeps the OCR text. Corrected paragraphs are marked
`corrected: true`, still `verified: false`: they are machine-corrected, not human-proofread.
The keys "1.1@1" mean "paragraphs from index 1 on" (paragraph 0 is hand-verified).
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "data" / "purports"
REPORT = ROOT / "docs" / "tamil-purport-correction-report.md"
# Rejected: Latin letters, invalid doubled vowel signs, Tamil digits, junk symbols, and digits glued
# to Tamil letters (OCR debris). Allowed: verse references such as "(7.22.39)" or "39-வது", and [ ] brackets.
BAD = re.compile(r"[A-Za-z]|[\u0BBE-\u0BCD]{2}|[\u0BE6-\u0BEF]|[|_\\{}<>~^*=#@$%&/]|[\u0B80-\u0BFF]\d|\d[\u0B80-\u0BFF]")
LENGTH_TOLERANCE = 0.12


JUNK_PARAGRAPH = 40  # an OCR paragraph this short that was emptied is stray characters, not content


def problems(old, new):
    """Return (reason, kept paragraphs). Emptied junk paragraphs are dropped; everything else is checked."""
    if not isinstance(new, list) or len(new) != len(old):
        return "paragraph count changed", None
    kept = []
    for i, (o, n) in enumerate(zip(old, new)):
        if not isinstance(n, str):
            return f"paragraph {i + 1} is not text", None
        if not n.strip():
            if len(o) < JUNK_PARAGRAPH:
                continue  # stray characters only; drop
            return f"paragraph {i + 1} empty", None
        if abs(len(n) - len(o)) > LENGTH_TOLERANCE * len(o):
            return f"paragraph {i + 1} length {len(n)} vs {len(o)}", None
        if BAD.search(n):
            return f"paragraph {i + 1} has stray characters", None
        letters = sum(1 for c in n if "\u0B80" <= c <= "\u0BFF")
        if letters < 0.8 * len(n.replace(" ", "")):
            return f"paragraph {i + 1} is not mostly Tamil", None
        kept.append(n.strip())
    if not kept:
        return "nothing left after cleaning", None
    return None, kept


def main():
    work = Path(sys.argv[1])
    corrected, rejected, missing, uncertain = {}, [], [], []
    for infile in sorted((work / "in").glob("p-*.json")):
        outfile = work / "out" / infile.name
        old = json.loads(infile.read_text())
        if not outfile.exists():
            missing += list(old)
            continue
        try:
            new = json.loads(outfile.read_text())
        except json.JSONDecodeError as e:
            rejected.append(f"- **{infile.stem}**: output is not valid JSON ({e}); {len(old)} purports keep OCR text")
            continue
        uncertain += [f"{infile.stem}: {u}" for u in new.get("uncertain", [])]
        for key, paras in old.items():
            why, kept = problems(paras, new.get(key))
            if why:
                rejected.append(f"- **{key}**: {why}; OCR text kept")
            else:
                corrected[key] = kept
    # the single-verse test run (2.46) lives next to the batches
    test = work / "out" / "test-2.46.json"
    if test.exists():
        t = json.loads(test.read_text())
        old = json.loads((work / "in" / "test-2.46.json").read_text())
        why, kept = problems(old["2.46"], t.get("2.46"))
        if why:
            rejected.append(f"- **2.46**: {why}; OCR text kept")
        else:
            corrected["2.46"] = kept

    applied = 0
    for chapter in range(1, 19):
        path = OUT / f"chapter-{chapter}.json"
        data = json.loads(path.read_text())
        for ref, v in data.items():
            for key in (ref, f"{ref}@1"):
                if key in corrected and v.get("ta"):
                    start = int(key.split("@")[1]) if "@" in key else 0
                    ta = v["ta"]
                    v["ta"] = ta[:start] + [{"text": t, "verified": False, "corrected": True} for t in corrected[key]]
                    applied += 1
        path.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n")
    lines = ["# Tamil purport correction report", "",
             "Machine-corrected OCR (not human-proofread). Generated by `scripts/merge_tamil_purport_corrections.py`.", "",
             f"- Purports corrected and applied: **{applied}**",
             f"- Kept as raw OCR (failed a guard): **{len(rejected)}**",
             f"- Kept as raw OCR (no corrected output): **{len(missing)}**",
             f"- Fragments the correcting agents flagged as uncertain: **{len(uncertain)}**", "",
             "## Kept as raw OCR", ""] + (rejected or ["- none"]) + ["", "## Uncertain fragments", ""] + [f"- {u}" for u in uncertain]
    REPORT.write_text("\n".join(lines) + "\n")
    print(dict(applied=applied, rejected=len(rejected), missing=len(missing), uncertain=len(uncertain)))


if __name__ == "__main__":
    main()
