"""Import Tamil purports (பொருளுரை) from the OCR'd Tamil book into src/data/purports/chapter-N.json.

Usage: python3 scripts/import_tamil_purports.py

Reuses the verse alignment of scripts/import_tamil_book.py. The text is unproofread OCR, so only
mechanical, non-speculative cleanup is applied (pure-Latin/symbol garbage tokens are dropped, the
invalid doubled vowel sign is fixed, page footers are removed). Purports with heavy damage are
left out and listed in docs/tamil-purport-import-report.md. Verses that already carry a
hand-verified paragraph (1.1) are never overwritten.
"""

import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import import_tamil_book as book  # noqa: E402

ROOT = book.ROOT
OUT = ROOT / "src" / "data" / "purports"
REPORT = ROOT / "docs" / "tamil-purport-import-report.md"
PURPORT_LABEL = "பொருளுரை"
MAX_JUNK_RATIO = 0.08  # share of whitespace-separated tokens that were pure garbage
NOISE_LINE = re.compile(r"verses\s*Page|^பக்கம் \d+$|^பகவத் கீதை உண்மையுருவில்$")
GARBAGE_TOKEN = re.compile(r"^[^஀-௿]*$")  # no Tamil letter at all: Latin, digits, symbols, Devanagari
TAMIL_DIGITS = re.compile(r"[௦-௯]")
PARAGRAPH_CHARS = 650  # soft paragraph size; the book's own paragraph breaks are not in the OCR


def purport_blocks(chapter):
    """[(title, [lines])] with the lines that follow each block's பொருளுரை label."""
    src = (book.BOOK / f"chapter_{chapter:02d}.html").read_text(encoding="utf-8")
    titles, lines, owner = [], [], None
    for m in book.TOKEN_RE.finditer(src):
        kind, body = m[1], book.clean(m[2] if m[1] else m[3])
        if kind == "verse-title":
            titles.append(body)
            lines.append([])
            owner = None
        elif kind == "section-label":
            owner = len(titles) - 1 if body == PURPORT_LABEL and titles else None
        elif owner is not None and body and not NOISE_LINE.search(body):
            lines[owner].append(body)
    return list(zip(titles, lines))


def tidy(lines):
    text = " ".join(lines).replace("ூு", "ு")
    tokens = text.split()
    kept = [t for t in tokens if not GARBAGE_TOKEN.match(t) and not TAMIL_DIGITS.search(t)]
    junk = 1 - len(kept) / len(tokens) if tokens else 1
    text = " ".join(kept)
    text = re.sub(r"\s+([,.;:?!])", r"\1", text)
    return text, junk


def paragraphs(text):
    """Group sentences into paragraphs of roughly PARAGRAPH_CHARS."""
    sentences = re.split(r"(?<=[.?!])\s+", text)
    out, cur = [], ""
    for s in sentences:
        cur = f"{cur} {s}".strip()
        if len(cur) >= PARAGRAPH_CHARS:
            out.append(cur)
            cur = ""
    if cur:
        out.append(cur)
    return out


def main():
    OUT.mkdir(exist_ok=True)
    stats, report = dict(ok=0, none=0, damaged=0), []
    for chapter in range(1, 19):
        entries = json.loads((book.GITA / f"chapter-{chapter}.json").read_text())
        refs = [e["reference"] for e in entries]
        blocks = purport_blocks(chapter)
        mapping, _ = book.align(chapter, refs, blocks)
        path = OUT / f"chapter-{chapter}.json"
        data = json.loads(path.read_text()) if path.exists() else {}
        for ref in refs:
            existing = data.get(ref, {}).get("ta")
            if existing and existing[0].get("verified"):
                stats["ok"] += 1
                continue  # hand-verified: keep as is
            text, junk = tidy(blocks[mapping[ref]][1]) if ref in mapping else ("", 1)
            if len(text) < 60:
                stats["none"] += 1
                data.get(ref, {}).pop("ta", None)
                continue
            if junk > MAX_JUNK_RATIO:
                stats["damaged"] += 1
                report.append(f"- **{ref}**: {junk:.0%} of the OCR tokens were garbage; Tamil purport left out")
                data.get(ref, {}).pop("ta", None)
                continue
            data.setdefault(ref, {})["ta"] = [{"text": p, "verified": False} for p in paragraphs(text)]
            stats["ok"] += 1
        data = {k: v for k, v in data.items() if v}
        path.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n")
    REPORT.write_text("\n".join([
        "# Tamil purport import report", "",
        "Generated by `python3 scripts/import_tamil_purports.py`. The imported text is unproofread OCR.", "",
        f"- Imported: **{stats['ok']}**", f"- No purport found in the book: **{stats['none']}**",
        f"- Left out as too damaged: **{stats['damaged']}**", "", "## Left out", ""] + (report or ["- none"])) + "\n")
    print(stats)


if __name__ == "__main__":
    main()
