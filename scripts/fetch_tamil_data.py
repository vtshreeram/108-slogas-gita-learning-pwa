def parse_verses(source):
    body = source.split("ஸ்ரீமத் பகவத் கீதை :  முழு உரை", 1)[1]
    chapters = re.split(r"<center><h3[^>]*>", body, flags=re.I)
    if len(chapters) != 18:
        raise ValueError("Expected 18 chapters in the Tamil source")
    result = {}
    for chapter, block in enumerate(chapters, 1):
        text = unicodedata.normalize("NFC", html.unescape(re.sub(r"<[^>]+>", "\n", block)))
        matches = list(re.finditer(r"(?m)^\s*(\d+)\.\s+", text))
        numbers = [int(match[1]) for match in matches]
        expected = [47, 72, 43, 42, 29, 47, 30, 28, 34, 42, 55, 20, 35, 27, 20, 24, 28, 78][chapter - 1]
        if numbers != list(range(1, expected + 1)):
            raise ValueError(f"Missing, duplicate or reordered verse in chapter {chapter}")
        for index, match in enumerate(matches):
            end = matches[index + 1].start() if index + 1 < len(matches) else len(text)
            value = re.sub(r"\s+", " ", text[match.end():end]).strip()
            # Speaker introductions belong to the following verse in this edition.
            value = re.sub(r"\s*(?:சஞ்ஜயன்|அர்ஜுனன்|ஸ்ரீபகவான்) சொல்லுகிறான்:\s*$", "", value)
            value = value.split("ஸ்ரீமத் பகவத் கீதை நிறைவு பெற்றது.")[0]
            value = re.sub(r"\s*-{3,}\s*$", "", value).strip()
            result[f"{chapter}.{match[1]}"] = value
    result.update(CORRECTIONS)
    return result


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path)
    parser.add_argument("--force-bharati", action="store_true", help="overwrite Tamil in shlokas.ts with Bharati's text")
    args = parser.parse_args()
    if not args.force_bharati:
        raise SystemExit("Tamil now comes from the Tamil book: use scripts/import_tamil_book.py. "
                         "Pass --force-bharati only to deliberately revert the 108 to Bharati's text.")
    source = args.source.read_text(encoding="utf-8") if args.source else urlopen(SOURCE, timeout=30).read().decode("utf-8")
    verses = parse_verses(source)
    path = ROOT / "src/lib/shlokas.ts"
    before, data = path.read_text().split("export const SHLOKAS: Shloka[] = ", 1)
    array, after = data.split("\n];", 1)
    shlokas = json.loads(array + "\n]")
    if len(shlokas) != 108:
        raise ValueError("Expected 108 entries; refusing to overwrite dataset")
    for shloka in shlokas:
        match = re.fullmatch(r"(\d+)\.(\d+)(?:-(\d+))?", shloka["reference"])
        if not match:
            raise ValueError(f"Invalid reference: {shloka['reference']}")
        chapter, start = int(match[1]), int(match[2])
        if (chapter, start) != (shloka["chapter"], shloka["verse"]):
            raise ValueError(f"Reference mismatch: {shloka['id']}")
        end = int(match[3] or start)
        shloka["tamil"] = "\n".join(verses[f"{chapter}.{verse}"] for verse in range(start, end + 1))
        # The former OCR commentary cannot be attributed to this Tamil edition.
        shloka.pop("tamilPurport", None)
    path.write_text(before + "export const SHLOKAS: Shloka[] = " + json.dumps(shlokas, ensure_ascii=False, indent=2) + ";" + after)
    print(f"Updated {len(shlokas)} Tamil entries from {SOURCE}")


if __name__ == "__main__":
    main()
